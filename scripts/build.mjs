import { cpSync, mkdirSync, rmSync, writeFileSync, readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('../', import.meta.url));
process.chdir(root);
const html = readFileSync('pizza-computational-lab/index.html', 'utf8');
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)];
for (const [i, match] of scripts.entries()) new Script(match[1], { filename: `inline-module-${i}.js` });
assert(scripts.length >= 6, 'Missing application modules');
assert(!/<script\b[^>]*\bsrc\s*=/i.test(html), 'The app must keep its offline runtime');
assert(html.includes('SPDX-License-Identifier: GPL-3.0-only'));
assert(readFileSync('LICENSE', 'utf8') === readFileSync('COPYING', 'utf8'));
rmSync('_site', { recursive: true, force: true });
mkdirSync('_site', { recursive: true });
const publicFiles = ['index.html', '404.html', 'pizza-computational-lab', 'assets', 'COPYING', 'LICENSES', 'THIRD_PARTY_NOTICES.md'];
for (const path of publicFiles) cpSync(path, `_site/${path}`, { recursive: true });
writeFileSync('_site/.nojekyll', '');
assert(readFileSync('_site/pizza-computational-lab/index.html').equals(readFileSync('pizza-computational-lab/index.html')));
assert.deepEqual(readdirSync('_site').sort(), [...publicFiles, '.nojekyll'].sort());
console.log(`Built _site/: ${publicFiles.length} allowlisted entries; ${scripts.length} inline modules parse correctly.`);
